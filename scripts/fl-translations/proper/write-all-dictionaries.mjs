const { MANUAL_KEYS } = await import("./manual-keys.mjs");

function translate(source, rules, locale) {
  const out = {};
  for (const key of enKeys) {
    if (MANUAL_KEYS[locale]?.[key]) out[key] = MANUAL_KEYS[locale][key];
    else out[key] = applyRules(source[key], rules);
  }
  return out;
}

function escapeTs(s) {
  return s.replace(/\\/g, "\\\\").replace(/"/g, '\\"');
}

function writeDictionary(outDir, keys, map, locale) {
  fs.mkdirSync(outDir, { recursive: true });
  const lines = keys.map((k) => `  "${escapeTs(k)}": "${escapeTs(map[k])}",`);
  fs.writeFileSync(
    path.join(outDir, `${locale}.ts`),
    `/* Generated from the canonical English source. */\nexport const dictionary: Record<string, string> = {\n${lines.join("\n")}\n};\n`,
  );
}

