function keepBrands(t) {
  let o = t;
  for (const b of KEEP) o = o.split(b).join(`\0${b}\0`);
  return o;
}
function restoreBrands(t) {
  return t.replace(/\0/g, "");
}
function applyRules(t, rules) {
  let o = keepBrands(t);
  for (const [a, b] of rules) o = o.split(a).join(b);
  return restoreBrands(o);
}

