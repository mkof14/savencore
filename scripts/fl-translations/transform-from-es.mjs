function translateKey(enKey, locale) {
  if (MANUAL[locale]?.[enKey]) return MANUAL[locale][enKey];
  const esVal = es[enKey];
  if (!esVal) return enKey;
  const rules = LOCALE_RULES[locale];
  return applyRules(esVal, rules);
}

function writeModule(name, obj) {
  const lines = Object.entries(obj).map(
    ([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`,
  );
  fs.writeFileSync(
    path.join(dir, name),
    `/** Locale module (D-0161) — generated from es transforms + manual overrides. */\nexport const translations = {\n${lines.join("\n")}\n};\n`,
  );
}

const outDir = path.join(root, "tmp/translations");
const localesDir = path.join(dir, "locales");
fs.mkdirSync(outDir, { recursive: true });
fs.mkdirSync(localesDir, { recursive: true });

for (const locale of ["fr", "ja", "zh-cn", "ar", "he", "ru", "uk"]) {
  const out = {};
  for (const key of enKeys) {
    out[key] = translateKey(key, locale);
  }
  fs.writeFileSync(
    path.join(outDir, `${locale}.json`),
    JSON.stringify(out, null, 2) + "\n",
  );
  fs.writeFileSync(
    path.join(localesDir, `${locale}.json`),
    JSON.stringify(out, null, 2) + "\n",
  );
  writeModule(
    `${locale}-flagship.mjs`,
    Object.fromEntries(flagshipKeys.map((k) => [k, out[k]])),
  );
  writeModule(
    `${locale}-legal.mjs`,
    Object.fromEntries(legalKeys.map((k) => [k, out[k]])),
  );
  const stillEn = enKeys.filter((k) => out[k] === k).length;
  console.log(`${locale}: wrote 360 entries (${stillEn} keys still match EN)`);
}
